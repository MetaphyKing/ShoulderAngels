# The embedded reasoning model. Override per-call with --model or the
# ANTHROPIC_MODEL environment variable.
DEFAULT_MODEL = os.environ.get("ANTHROPIC_MODEL", "claude-haiku-4-5")
DEFAULT_MAX_TOKENS = 1024
API_URL = "https://api.anthropic.com/v1/messages"
ANTHROPIC_VERSION = "2023-06-01"

VALID_CHOICES = ("safe", "bold")
VALID_BACKENDS = ("anthropic", "command")


# --------------------------------------------------------------------------- #
# Embedded LLM core (shared shape across all Organism tools)
# --------------------------------------------------------------------------- #
class LLMError(RuntimeError):
    """Raised when the embedded model cannot be reached or returns garbage."""


@runtime_checkable
class Completer(Protocol):
    """Duck-type contract for anything that can supply a completion.

    Agent hosts (Grok Bot, a subagent, a recorded fixture) implement this
    instead of calling Anthropic. ``ShoulderAngels`` only needs ``complete``.
    """

    def complete(self, prompt: str, system: str = "") -> str: ...


class LLMClient:
    """Minimal, dependency-free client for the Anthropic Messages API.

    Designed to fail loudly and helpfully: a missing key, a network blip, or a
    malformed response each produce a clear ``LLMError`` instead of an opaque
    stack trace. Transient HTTP errors (429/5xx) are retried with backoff.
    """

    def __init__(
        self,
        model: str = DEFAULT_MODEL,
        max_tokens: int = DEFAULT_MAX_TOKENS,
        timeout: float = 60.0,
        max_retries: int = 3,
        api_key: str | None = None,
        api_url: str = API_URL,
    ) -> None:
        self.model = model
        self.max_tokens = max_tokens
        self.timeout = timeout
        self.max_retries = max(1, max_retries)
        self._api_key = api_key
        self.api_url = api_url

    @property
    def api_key(self) -> str:
        key = self._api_key or os.environ.get("ANTHROPIC_API_KEY")
        if not key:
            raise LLMError(
                "ANTHROPIC_API_KEY is not set. Export your key first:\n"
                "    export ANTHROPIC_API_KEY=sk-ant-..."
            )
        return key

    def complete(self, prompt: str, system: str = "") -> str:
        """Send a single-turn prompt and return the model's text response."""
        body: dict[str, Any] = {
            "model": self.model,
            "max_tokens": self.max_tokens,
            "messages": [{"role": "user", "content": prompt}],
        }
        if system:
            body["system"] = system

        data = json.dumps(body).encode("utf-8")
        last_err: Exception | None = None

        for attempt in range(1, self.max_retries + 1):
            req = urllib.request.Request(
                self.api_url,
                data=data,
                headers={
                    "x-api-key": self.api_key,
                    "anthropic-version": ANTHROPIC_VERSION,
                    "content-type": "application/json",
                },
            )
            try:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    payload = json.loads(resp.read().decode("utf-8"))
                return self._extract_text(payload)
            except urllib.error.HTTPError as exc:
                detail = exc.read().decode("utf-8", "replace")[:500]
                if exc.code in (408, 429, 500, 502, 503, 529) and attempt < self.max_retries:
                    time.sleep(min(2.0 * attempt, 8.0))
                    last_err = exc
                    continue
                raise LLMError(f"API HTTP {exc.code}: {detail}") from exc
            except urllib.error.URLError as exc:
                if attempt < self.max_retries:
                    time.sleep(min(2.0 * attempt, 8.0))
                    last_err = exc
                    continue
                raise LLMError(f"Network error reaching the model: {exc.reason}") from exc
            except (KeyError, IndexError, ValueError) as exc:
                raise LLMError(f"Unexpected API response shape: {exc}") from exc

        raise LLMError(f"Exhausted {self.max_retries} retries: {last_err}")

    @staticmethod
    def _extract_text(payload: dict[str, Any]) -> str:
        content = payload.get("content")
        if not content:
            raise LLMError(f"API returned no content: {payload}")
        parts = [block.get("text", "") for block in content if block.get("type") == "text"]
        text = "".join(parts).strip()
        if not text:
            raise LLMError("API returned an empty text response")
        return text


AnthropicClient = LLMClient


class CallableClient:
    """Wrap any ``(prompt, system) -> text`` callable as a :class:`Completer`."""

    def __init__(self, fn: Callable[[str, str], str]) -> None:
        self._fn = fn

    def complete(self, prompt: str, system: str = "") -> str:
        text = self._fn(prompt, system)
        if not isinstance(text, str) or not text.strip():
            raise LLMError("Callable completer returned empty output")
        return text


class CommandClient:
    """Run an external command as a :class:`Completer`.

    Writes one JSON object ``{"prompt": ..., "system": ...}`` to the child's
    stdin. Reads stdout as JSON ``{"text": ...}`` or as raw text. Raises
    ``LLMError`` on non-zero exit, empty output, or timeout.
    """

    def __init__(
        self,
        command: str | Sequence[str],
        timeout: float = 60.0,
    ) -> None:
        if isinstance(command, str):
            self.command = shlex.split(command)
        else:
            self.command = list(command)
        if not self.command:
            raise LLMError("complete command is empty")
        self.timeout = timeout

    def complete(self, prompt: str, system: str = "") -> str:
        payload = json.dumps({"prompt": prompt, "system": system}).encode("utf-8")
        try:
            proc = subprocess.run(
                self.command,
                input=payload,
                capture_output=True,
                timeout=self.timeout,
            )
        except subprocess.TimeoutExpired as exc:
            raise LLMError(
                f"complete command timed out after {self.timeout}s"
            ) from exc
        except OSError as exc:
            raise LLMError(f"failed to run complete command: {exc}") from exc

        if proc.returncode != 0:
            err = (proc.stderr or b"").decode("utf-8", "replace")[:500]
            raise LLMError(f"complete command exited {proc.returncode}: {err}")

        return self._parse_output((proc.stdout or b"").decode("utf-8", "replace"))

    @staticmethod
    def _parse_output(stdout: str) -> str:
        text = stdout.strip()
        if not text:
            raise LLMError("complete command returned empty output")
        try:
            parsed = json.loads(text)
        except json.JSONDecodeError:
            return text
        if isinstance(parsed, dict) and "text" in parsed:
            out = parsed["text"]
            if not isinstance(out, str) or not out.strip():
                raise LLMError("complete command returned empty text")
            return out
        return text


def extract_json(text: str) -> Any:
    """Best-effort parse of a JSON value embedded in arbitrary model output.

    Handles raw JSON, ```json fenced blocks, and JSON preceded by prose.
    Returns the parsed value, or raises ``ValueError`` if nothing parses.
    """
    text = text.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    fence = re.search(r"```(?:json)?\s*(.*?)```", text, re.DOTALL)
    if fence:
        try:
            return json.loads(fence.group(1).strip())
        except json.JSONDecodeError:
            pass

    # Fall back to the first balanced {...} or [...] span.
    for opener, closer in (("{", "}"), ("[", "]")):
        start = text.find(opener)
        end = text.rfind(closer)
        if 0 <= start < end:
            try:
                return json.loads(text[start : end + 1])
            except json.JSONDecodeError:
                continue
    raise ValueError("No parseable JSON found in model output")


