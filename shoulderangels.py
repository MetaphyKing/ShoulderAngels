def _interactive_chooser(strategies: dict[str, dict[str, Any]]) -> str:
    print(f"\n🔰 SAFE PATH: {strategies['safe'].get('description', 'N/A')}")
    print(f"   effort={strategies['safe'].get('effort')} "
          f"risk={strategies['safe'].get('risk')} upside={strategies['safe'].get('upside')}")
    print(f"\n⚡ BOLD PATH: {strategies['bold'].get('description', 'N/A')}")
    print(f"   effort={strategies['bold'].get('effort')} "
          f"risk={strategies['bold'].get('risk')} upside={strategies['bold'].get('upside')}")
    try:
        answer = input("\nChoose [safe/bold/both]: ").strip().lower()
    except EOFError:
        answer = "safe"
    return answer or "safe"


def _env_backend() -> str:
    raw = os.environ.get("SHOULDERANGELS_BACKEND", "anthropic").strip().lower()
    return raw or "anthropic"


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="shoulderangels",
        description="Two voices debate your coding path forward.",
    )
    ap.add_argument("target", nargs="?", help="the task/goal, or a path to a file describing it")
    ap.add_argument("--choose", choices=("safe", "bold", "both"),
                    help="force a path without prompting (pipeline-friendly)")
    ap.add_argument("--json", action="store_true", help="emit JSON")
    ap.add_argument("--model", default=DEFAULT_MODEL, help=f"model id (default: {DEFAULT_MODEL})")
    ap.add_argument("--max-tokens", type=int, default=DEFAULT_MAX_TOKENS, help="max tokens per call")
    ap.add_argument(
        "--backend",
        choices=VALID_BACKENDS,
        default=_env_backend(),
        help="completion backend (default: anthropic; also $SHOULDERANGELS_BACKEND)",
    )
    ap.add_argument(
        "--complete-cmd",
        default=os.environ.get("SHOULDERANGELS_COMPLETE_CMD"),
        metavar="CMD",
        help="external completer command; required for --backend command "
             "(also $SHOULDERANGELS_COMPLETE_CMD)",
    )
    ap.add_argument("--no-store", action="store_true", help="do not record this decision to history")
    ap.add_argument("--history", action="store_true", help="print decision history and exit")
    ap.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return ap


def client_from_args(args: argparse.Namespace) -> Completer:
    """Build a Completer from parsed CLI flags. Anthropic stays the default."""
    backend = (args.backend or "anthropic").strip().lower()
    if backend == "command":
        cmd = (args.complete_cmd or "").strip()
        if not cmd:
            build_parser().error(
                "--complete-cmd is required when --backend is command "
                "(or set SHOULDERANGELS_COMPLETE_CMD)"
            )
        return CommandClient(cmd)
    if backend != "anthropic":
        build_parser().error(
            f"invalid --backend {args.backend!r} (choose from {', '.join(VALID_BACKENDS)})"
        )
    return LLMClient(model=args.model, max_tokens=args.max_tokens)


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.history:
        # History does not call the model; skip backend / API-key requirements.
        tool = ShoulderAngels()
        history = tool.load_history()
        print(json.dumps(history, indent=2) if args.json else f"{len(history)} decision(s) recorded")
        if not args.json:
            for item in history:
                print(f"  • [{item.get('chosen_path')}] {item.get('target')}")
        return 0

    if not args.target:
        build_parser().error("a target task is required (or use --history)")

    # Interactive only when attached to a TTY and no choice was forced.
    chooser = _interactive_chooser if (args.choose is None and sys.stdin.isatty()) else None

    try:
        tool = ShoulderAngels(client=client_from_args(args))
        result = tool.run(
            args.target,
            choice=args.choose,
            chooser=chooser,
            store=not args.no_store,
        )
    except LLMError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"\n✅ Chosen path: {result['chosen_path']}")
        for path, outcome in result["predicted_outcomes"].items():
            print(f"\n— Predicted outcomes ({path}) —\n{outcome}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
