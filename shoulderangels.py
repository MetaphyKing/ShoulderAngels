class ShoulderAngels:
    """Generate, choose between, and forecast safe vs. bold dev strategies."""

    STRATEGY_SYSTEM = (
        "You are a development strategist. For the user's task, return ONLY a "
        "JSON object with two keys, 'safe' and 'bold'. 'safe' is the boring, "
        "low-risk, guaranteed approach; 'bold' is the ambitious, experimental, "
        "higher-risk approach. Each value is an object with keys: 'description', "
        "'effort' (low|medium|high), 'risk' (low|medium|high), and 'upside' "
        "(a short phrase). Output JSON only, no prose."
    )

    def __init__(self, store: Path | None = None, client: Completer | None = None) -> None:
        self.store = store or Path.home() / ".shoulderangels" / "history.json"
        self.client = client or LLMClient()

    # -- core mechanism: the embedded LLM ----------------------------------- #
    def _ask(self, prompt: str, system: str = "") -> str:
        """Query the embedded reasoning model (the tool's core mechanism)."""
        return self.client.complete(prompt, system=system)

    # -- strategy generation ------------------------------------------------ #
    def propose(self, target: str) -> dict[str, dict[str, Any]]:
        """Return validated {'safe': {...}, 'bold': {...}} strategies."""
        raw = self._ask(
            f"Task: {target}\n\nProvide two competing development strategies.",
            system=self.STRATEGY_SYSTEM,
        )
        try:
            parsed = extract_json(raw)
        except ValueError:
            parsed = {}
        return self._normalize(parsed, raw)

    @staticmethod
    def _normalize(parsed: Any, raw: str) -> dict[str, dict[str, Any]]:
        if not isinstance(parsed, dict):
            parsed = {}
        out: dict[str, dict[str, Any]] = {}
        for key in VALID_CHOICES:
            val = parsed.get(key)
            if not isinstance(val, dict):
                val = {"description": (raw.strip() or f"No {key} strategy returned")[:280]}
            val.setdefault("description", f"No {key} description")
            val.setdefault("effort", "unknown")
            val.setdefault("risk", "low" if key == "safe" else "high")
            val.setdefault("upside", "n/a")
            out[key] = val
        return out

    def forecast(self, strategy: dict[str, Any]) -> str:
        """Predict three concrete outcomes for the chosen strategy."""
        desc = strategy.get("description", "")
        return self._ask(
            f"Predict realistic outcomes if we pursue this approach:\n{desc}\n\n"
            "List exactly 3 concrete, specific results.",
            system="Be specific and practical. No hedging.",
        )

    # -- orchestration ------------------------------------------------------ #
    def run(
        self,
        target: str,
        choice: str | None = None,
        chooser: Callable[[dict[str, dict[str, Any]]], str] | None = None,
        store: bool = True,
    ) -> dict[str, Any]:
        """Full flow: propose → choose → forecast → record.

        ``choice`` forces a path ('safe'/'bold'/'both'). If omitted and a
        ``chooser`` is supplied, it is asked interactively. With neither, the
        decision defaults to 'safe' (pipeline-friendly, never blocks).
        """
        target, subject = self._bind_subject(target)
        strategies = self.propose(target)

        if choice is None and chooser is not None:
            choice = chooser(strategies)
        if choice is None:
            choice = "safe"
        choice = choice.strip().lower()

        if choice == "both":
            forecasts = {k: self.forecast(strategies[k]) for k in VALID_CHOICES}
            selected: Any = strategies
        else:
            if choice not in VALID_CHOICES:
                choice = "safe"
            selected = strategies[choice]
            forecasts = {choice: self.forecast(selected)}

        result = {
            "target": target,
            "chosen_path": choice,
            "strategy": selected,
            "predicted_outcomes": forecasts,
            "safe_risk": strategies["safe"].get("risk", "low"),
            "bold_upside": strategies["bold"].get("upside", "high"),
            "timestamp": datetime.now(timezone.utc).isoformat(),
            **subject,
        }
        if store:
            self._record(result)
        return result

    @staticmethod
    def _digest(raw: bytes) -> dict[str, Any]:
        h = hashlib.sha256(raw).hexdigest()
        return {
            "subject_size": len(raw),
            "subject_sha256": h,
            "subject_sha16": h[:16],
        }

    @staticmethod
    def _bind_subject(target: Any) -> tuple[str, dict[str, Any]]:
        """Resolve *target* to prompt text AND a digest of the bytes fed.

        File paths: hash the file bytes as they sit on disk (never the
        stripped text the model sees). Plain strings and dicts: hash
        UTF-8 of the text that will be proposed on. Size is always
        bytes, never a character count.
        """
        meta: dict[str, Any] = {"subject_kind": "text"}
        if isinstance(target, dict):
            text = target.get("task") or target.get("target") or json.dumps(target)
            meta.update(ShoulderAngels._digest(text.encode("utf-8")))
            return text, meta
        if isinstance(target, str):
            candidate = Path(target)
            try:
                if candidate.is_file():
                    raw = candidate.read_bytes()
                    meta = {
                        "subject_kind": "file",
                        "subject_path": str(candidate.resolve()),
                        **ShoulderAngels._digest(raw),
                    }
                    return raw.decode("utf-8").strip(), meta
            except OSError:
                pass
            meta.update(ShoulderAngels._digest(target.encode("utf-8")))
            return target, meta
        text = str(target)
        meta.update(ShoulderAngels._digest(text.encode("utf-8")))
        return text, meta

    @staticmethod
    def _coerce_target(target: Any) -> str:
        """Accept a plain string, a JSON object/dict, or a file path."""
        text, _ = ShoulderAngels._bind_subject(target)
        return text

    # -- history persistence ------------------------------------------------ #
    def record(self, result: dict[str, Any]) -> None:
        """Append a finished result dict to history without calling the model.

        Agent hosts that already have a completed decision can persist it here
        instead of re-running ``propose`` / ``run``.
        """
        if not isinstance(result, dict):
            raise TypeError("result must be a dict")
        self._record(result)

    def _record(self, result: dict[str, Any]) -> None:
        history = self.load_history()
        history.append(result)
        self.store.parent.mkdir(parents=True, exist_ok=True)
        self.store.write_text(json.dumps(history, indent=2), encoding="utf-8")

    def load_history(self) -> list[dict[str, Any]]:
        if not self.store.exists():
            return []
        try:
            data = json.loads(self.store.read_text(encoding="utf-8"))
            return data if isinstance(data, list) else []
        except (json.JSONDecodeError, OSError):
            return []


